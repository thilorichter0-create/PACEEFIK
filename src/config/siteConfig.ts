export function isFilled(value: string | undefined): value is string {
  return Boolean(value && value.trim() && !/^\{\{[^}]+\}\}$/.test(value.trim()));
}

export function whatsappHrefFor(pageName: string, message?: string) {
  if (!isFilled(siteConfig.contact.whatsappUrl)) return undefined;
  try {
    const url = new URL(siteConfig.contact.whatsappUrl);
    if (url.protocol !== "https:") return undefined;
    url.searchParams.set("text", message ?? `Hello Paceefik Engineering, I would like to enquire about a project. (Sent from: ${pageName})`);
    return url.toString();
  } catch {
    return undefined;
  }
}

export function siteStyleVariables(): React.CSSProperties {
  return Object.fromEntries(Object.entries(siteConfig.colours).map(([name, value]) => [`--site-${name}`, value])) as React.CSSProperties;
}
